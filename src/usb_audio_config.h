#ifndef USB_AUDIO_CONFIG_H_
#define USB_AUDIO_CONFIG_H_

#ifndef USB_AUDIO_CLASS_VERSION
#define USB_AUDIO_CLASS_VERSION 2
#endif

#if USB_AUDIO_CLASS_VERSION != 1 && USB_AUDIO_CLASS_VERSION != 2
#error "USB_AUDIO_CLASS_VERSION must be 1 or 2"
#endif

#ifndef USB_BRINGUP_LEVEL
#define USB_BRINGUP_LEVEL 3
#endif

#if USB_BRINGUP_LEVEL < 0 || USB_BRINGUP_LEVEL > 3
#error "USB_BRINGUP_LEVEL must be 0, 1, 2, or 3"
#endif

#define USB_CDC_ENABLED (USB_BRINGUP_LEVEL == 3)

#define USB_AUDIO_PRODUCT_NAME "Pico2 UAC12 USB DDC"

#define USB_CDC_WEATHER_INTERFACE_NAME "Weather Service"
#define USB_CDC_DIAGNOSTICS_INTERFACE_NAME "USB Diagnostics"
#define USB_CDC_LEGACY_INTERFACE_NAME "Weather/Diagnostic CDC"
#define USB_CDC_WEATHER_STRING_INDEX 5
#define USB_CDC_DIAGNOSTICS_STRING_INDEX 6

#define USB_CDC_WEATHER_EP_NOTIF 0x83
#define USB_CDC_WEATHER_EP_OUT 0x02
#define USB_CDC_WEATHER_EP_IN 0x82
#define USB_CDC_DIAGNOSTICS_EP_NOTIF 0x85
#define USB_CDC_DIAGNOSTICS_EP_OUT 0x04
#define USB_CDC_DIAGNOSTICS_EP_IN 0x84

#endif
