"""Generate src/weather_font.h: 16x16 bitmaps of the Japanese glyphs used by the Weather screen.

Requires Pillow and a Japanese font (Noto Sans JP, SIL OFL 1.1, is recommended):
    py tools\\generate_weather_font.py C:\\Windows\\Fonts\\NotoSansJP-VF.ttf
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# The order defines the character codes 0x80, 0x81, ... used by display_rta.c.
GLYPHS = "晴曇雨雪時々れりのち今日明最高低℃降水確率０１２３４５６７８９％"
SIZE = 16
THRESHOLD = 110


def render(font: ImageFont.FreeTypeFont, char: str) -> list[int]:
    image = Image.new("L", (SIZE * 4, SIZE * 4), 0)
    draw = ImageDraw.Draw(image)
    draw.text((SIZE * 2, SIZE * 2), char, font=font, fill=255, anchor="mm")
    box = image.getbbox()
    if box is None:
        raise ValueError(f"The font has no glyph for {char}")
    left = box[0] + (box[2] - box[0] - SIZE) // 2
    top = box[1] + (box[3] - box[1] - SIZE) // 2
    cell = image.crop((left, top, left + SIZE, top + SIZE))
    rows = []
    for y in range(SIZE):
        value = 0
        for x in range(SIZE):
            if cell.getpixel((x, y)) >= THRESHOLD:
                value |= 0x8000 >> x
        rows.append(value)
    return rows


def main() -> int:
    font_path = sys.argv[1] if len(sys.argv) > 1 else r"C:\Windows\Fonts\NotoSansJP-VF.ttf"
    font = ImageFont.truetype(font_path, SIZE)
    try:
        font.set_variation_by_axes([500])
    except (OSError, AttributeError):
        pass

    lines = [
        "// Generated by tools/generate_weather_font.py from Noto Sans JP (SIL Open Font License 1.1).",
        "// Do not edit by hand.",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "typedef struct",
        "{",
        "\tconst char *utf8;",
        "\tuint16_t rows[16];",
        "} display_jp_glyph_t;",
        "",
        "static const display_jp_glyph_t weather_jp_glyphs[] = {",
    ]
    for char in GLYPHS:
        rows = render(font, char)
        for row in rows:
            print("".join("#" if row & (0x8000 >> x) else "." for x in range(SIZE)))
        print()
        values = ", ".join(f"0x{row:04X}" for row in rows)
        lines.append(f'\t{{"{char}", {{{values}}}}},')
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    Path(__file__).resolve().parent.parent.joinpath("src", "weather_font.h").write_text(
        "\n".join(lines) + "\n", encoding="utf-8", newline="\n"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
